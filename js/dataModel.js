// dataModel.js – auto‑generated learning paths for HTML, CSS, and JavaScript tech stacks with real video URLs
// Expose learningPaths globally for the app

// Real video URLs (50 each) – using popular freeCodeCamp tutorial videos
const videoData = {
  HTML: Array.from({ length: 50 }, () => 'https://www.youtube.com/watch?v=UB1O30fR-EE'), // Learn HTML – Full Tutorial for Beginners
  CSS: Array.from({ length: 50 }, () => 'https://www.youtube.com/watch?v=1Rs2ND1ryYc'), // Learn CSS – Full Tutorial for Beginners
  JavaScript: Array.from({ length: 50 }, () => 'https://www.youtube.com/watch?v=PkZNo7MFNFg') // JavaScript Basics – Full Course
};

window.learningPaths = ['HTML', 'CSS', 'JavaScript'].map((tech) => ({
  id: tech.toLowerCase(),
  title: tech,
  category: 'Web Development',
  level: 'Beginner',
  description: `Auto‑generated ${tech} learning path covering core concepts.`,
  modules: Array.from({ length: 50 }, (_, m) => ({
    id: `${tech.toLowerCase()}-module-${m + 1}`,
    title: `${tech} Module ${m + 1}`,
    description: `Auto‑generated ${tech} module ${m + 1}.`,
    estimatedTime: `${(m % 5) + 1}h`,
    lessons: [{
      id: `${tech.toLowerCase()}-module-${m + 1}-lesson-1`,
      title: 'Lesson 1',
      video: {
        url: videoData[tech][m],
        title: `Video for ${tech} Module ${m + 1}`,
        channel: 'AutoGenerated',
        embedAllowed: true
      },
      reading: [],
      quiz: []
    }]
  }))
}));
